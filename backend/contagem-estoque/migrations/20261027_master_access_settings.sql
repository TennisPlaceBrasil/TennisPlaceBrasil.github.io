begin;
alter table public.manual_portal_members
  add column if not exists is_master boolean not null default false;

create table if not exists public.manual_portal_access_audit (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  target_user_id uuid not null,
  previous_master boolean not null,
  new_master boolean not null,
  previous_stores text[] not null default '{}'::text[],
  new_stores text[] not null default '{}'::text[],
  created_at timestamptz not null default now()
);
create index if not exists manual_portal_access_audit_created_at_idx
  on public.manual_portal_access_audit (created_at desc);
alter table public.manual_portal_access_audit enable row level security;
revoke all on table public.manual_portal_access_audit from public, anon, authenticated;
grant all on table public.manual_portal_access_audit to service_role;

do $$
declare changed integer;
begin
  update public.manual_portal_members m set is_master=true
  from auth.users u
  where u.id=m.user_id
    and lower(u.email) in ('alberto.guimaraes@tennisplacebrasil.com.br','paulo.ribeiro@tennisplacebrasil.com.br');
  get diagnostics changed=row_count;
  if changed<>2 then raise exception 'Expected exactly two MASTER accounts; updated %',changed; end if;
end $$;

create or replace function public.manual_portal_apply_user_access(
  p_actor uuid,p_target uuid,p_master boolean,p_stores text[]
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  target_profiles text[];
  target_active boolean;
  previous_master boolean;
  home_stores text[] := '{}'::text[];
  prior_extra text[] := '{}'::text[];
  before_stores text[] := '{}'::text[];
  after_stores text[] := '{}'::text[];
  all_stores text[] := '{}'::text[];
  desired text[] := '{}'::text[];
  master_count integer;
  audit_row bigint;
begin
  if not exists (select 1 from public.manual_portal_members where user_id=p_actor and active and is_master) then
    raise exception 'Somente um usuário MASTER ativo pode alterar acessos.';
  end if;
  if p_master is null or p_stores is null then raise exception 'Informe o perfil MASTER e a lista de lojas.'; end if;
  select profiles,is_master,active into target_profiles,previous_master,target_active
    from public.manual_portal_members where user_id=p_target for update;
  if not found then raise exception 'Usuário não encontrado.'; end if;
  if p_master and not coalesce('adm'=any(target_profiles),false) then
    raise exception 'MASTER só pode ser atribuído a uma conta administrativa.';
  end if;
  if p_master and not target_active then raise exception 'Ative a conta antes de atribuir MASTER.'; end if;

  select coalesce(array_agg(sigla order by sigla),'{}'::text[]) into all_stores
    from public.manual_portal_store_logins;
  select coalesce(array_agg(distinct t.value order by t.value),'{}'::text[]) into desired
    from unnest(p_stores) as t(value);
  if exists (select 1 from unnest(desired) as t(value) where not (t.value=any(all_stores))) then
    raise exception 'A lista contém uma loja inexistente.';
  end if;
  select coalesce(array_agg(sigla order by sigla),'{}'::text[]) into home_stores
    from public.manual_portal_store_logins where user_id=p_target;
  select coalesce(array_agg(sigla order by sigla),'{}'::text[]) into prior_extra
    from public.stockcount_user_store_access where user_id=p_target;
  if not (home_stores <@ desired) then raise exception 'O acesso à loja principal não pode ser removido.'; end if;

  if coalesce('adm'=any(target_profiles),false) or previous_master then before_stores:=all_stores;
  else select coalesce(array_agg(distinct t.value order by t.value),'{}'::text[]) into before_stores
    from unnest(home_stores||prior_extra) as t(value); end if;
  if coalesce('adm'=any(target_profiles),false) or p_master then after_stores:=all_stores;
  else after_stores:=desired; end if;

  if not coalesce('adm'=any(target_profiles),false) and not p_master then
    delete from public.stockcount_user_store_access where user_id=p_target;
    insert into public.stockcount_user_store_access(user_id,sigla)
      select p_target,t.value from unnest(desired) as t(value)
      where not (t.value=any(home_stores))
      on conflict (user_id,sigla) do nothing;
  end if;

  update public.manual_portal_members set is_master=p_master where user_id=p_target;
  select count(*) into master_count from public.manual_portal_members where active and is_master;
  if master_count<1 then raise exception 'O sistema precisa manter pelo menos um MASTER ativo.'; end if;

  if previous_master is distinct from p_master or before_stores is distinct from after_stores then
    insert into public.manual_portal_access_audit(actor_user_id,target_user_id,previous_master,new_master,previous_stores,new_stores)
      values(p_actor,p_target,previous_master,p_master,before_stores,after_stores) returning id into audit_row;
  end if;
  return jsonb_build_object('user_id',p_target,'is_master',p_master,'stores',after_stores,'audit_id',audit_row);
end $$;
revoke all on function public.manual_portal_apply_user_access(uuid,uuid,boolean,text[]) from public,anon,authenticated;
grant execute on function public.manual_portal_apply_user_access(uuid,uuid,boolean,text[]) to service_role;
commit;
